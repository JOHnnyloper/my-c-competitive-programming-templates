vector<int> z_function(const string &s) {
  int n = (int)s.size();
  vector<int> z(n, 0);
  int l = 0, r = 0;
  for (int i = 1; i < n; i++) {
    if (i <= r)
      z[i] = min(r - i + 1, z[i - l]);
    while (i + z[i] < n && s[z[i]] == s[i + z[i]])
      z[i]++;
    if (i + z[i] - 1 > r) {
      l = i;
      r = i + z[i] - 1;
    }
  }
  return z;
}
void run_case() {
  string s;
  cin >> s;
  vector<int> z = z_function(s);
  for (int x : z)
    cout << x << ' ';
}
